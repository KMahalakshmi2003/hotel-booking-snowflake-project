-- ==========================================================
-- CURATED LAYER
-- ==========================================================
USE DATABASE HOTEL_BOOKING_DB;

USE SCHEMA CURATED;

CREATE OR REPLACE TABLE CUSTOMER AS
SELECT
    CUSTOMER_ID,
    INITCAP(TRIM(FIRST_NAME)) AS FIRST_NAME,
    INITCAP(TRIM(LAST_NAME)) AS LAST_NAME,
    LOWER(TRIM(EMAIL)) AS EMAIL,
    PHONE_NUMBER,
    DATE_OF_BIRTH,
    INITCAP(TRIM(CITY)) AS CITY,
    INITCAP(TRIM(STATE)) AS STATE,
    UPPER(TRIM(COUNTRY)) AS COUNTRY,
    CREATED_DATE
FROM RAW.CUSTOMER;

CREATE OR REPLACE TABLE HOTEL AS
SELECT
    HOTEL_ID,
    INITCAP(TRIM(HOTEL_NAME)) AS HOTEL_NAME,
    STAR_RATING,
    INITCAP(TRIM(HOTEL_ADDRESS)) AS HOTEL_ADDRESS,
    INITCAP(TRIM(CITY)) AS CITY,
    INITCAP(TRIM(STATE)) AS STATE,
    UPPER(TRIM(COUNTRY)) AS COUNTRY,
    PHONE_NUMBER
FROM RAW.HOTEL;

CREATE OR REPLACE TABLE ROOM AS
SELECT
    ROOM_ID,
    HOTEL_ID,
    UPPER(TRIM(ROOM_NUMBER)) AS ROOM_NUMBER,
    INITCAP(TRIM(ROOM_TYPE)) AS ROOM_TYPE,
    PRICE_PER_NIGHT,
    CAPACITY,
    UPPER(TRIM(AVAILABILITY_STATUS)) AS AVAILABILITY_STATUS
FROM RAW.ROOM;

CREATE OR REPLACE TABLE BOOKING AS
SELECT
    BOOKING_ID,
    CUSTOMER_ID,
    ROOM_ID,
    CHECK_IN_DATE,
    CHECK_OUT_DATE,
    BOOKING_DATE,
    NUMBER_OF_GUESTS,
    UPPER(TRIM(BOOKING_STATUS)) AS BOOKING_STATUS
FROM RAW.BOOKING;

CREATE OR REPLACE TABLE PAYMENT AS
SELECT
    PAYMENT_ID,
    BOOKING_ID,
    PAYMENT_DATE,
    INITCAP(TRIM(PAYMENT_MODE)) AS PAYMENT_MODE,
    AMOUNT,
    UPPER(TRIM(PAYMENT_STATUS)) AS PAYMENT_STATUS,
    TRANSACTION_ID
FROM RAW.PAYMENT;

-- ===========================================
-- STEP 13: SQL JOINS
-- ===========================================

SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME,
    B.BOOKING_ID,
    B.CHECK_IN_DATE,
    B.CHECK_OUT_DATE,
    B.BOOKING_STATUS
FROM CUSTOMER C
INNER JOIN BOOKING B
ON C.CUSTOMER_ID = B.CUSTOMER_ID;

SELECT
    C.FIRST_NAME || ' ' || C.LAST_NAME AS CUSTOMER_NAME,
    H.HOTEL_NAME,
    R.ROOM_NUMBER,
    R.ROOM_TYPE,
    B.CHECK_IN_DATE,
    B.CHECK_OUT_DATE,
    P.AMOUNT,
    P.PAYMENT_MODE,
    P.PAYMENT_STATUS
FROM CUSTOMER C
INNER JOIN BOOKING B
    ON C.CUSTOMER_ID = B.CUSTOMER_ID
INNER JOIN ROOM R
    ON B.ROOM_ID = R.ROOM_ID
INNER JOIN HOTEL H
    ON R.HOTEL_ID = H.HOTEL_ID
INNER JOIN PAYMENT P
    ON B.BOOKING_ID = P.BOOKING_ID;

-- ==========================================================
-- ANALYTICS LAYER
-- ==========================================================
USE SCHEMA ANALYTICS;
CREATE OR REPLACE TABLE BOOKING_SUMMARY AS
SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME || ' ' || C.LAST_NAME AS CUSTOMER_NAME,
    H.HOTEL_NAME,
    R.ROOM_NUMBER,
    R.ROOM_TYPE,
    B.CHECK_IN_DATE,
    B.CHECK_OUT_DATE,
    DATEDIFF('DAY', B.CHECK_IN_DATE, B.CHECK_OUT_DATE) AS TOTAL_DAYS,
    P.AMOUNT,
    P.PAYMENT_MODE,
    P.PAYMENT_STATUS
FROM CURATED.CUSTOMER C
INNER JOIN CURATED.BOOKING B
    ON C.CUSTOMER_ID = B.CUSTOMER_ID
INNER JOIN CURATED.ROOM R
    ON B.ROOM_ID = R.ROOM_ID
INNER JOIN CURATED.HOTEL H
    ON R.HOTEL_ID = H.HOTEL_ID
INNER JOIN CURATED.PAYMENT P
    ON B.BOOKING_ID = P.BOOKING_ID;

-- ===========================================
-- VERIFICATION QUERIES
-- Report 1: Hotel Revenue Summary
-- ===========================================
--Which hotel earned the most revenue?

CREATE OR REPLACE TABLE HOTEL_REVENUE_SUMMARY AS
SELECT
    HOTEL_NAME,
    COUNT(*) AS TOTAL_BOOKINGS,
    SUM(AMOUNT) AS TOTAL_REVENUE,
    AVG(AMOUNT) AS AVERAGE_BOOKING_AMOUNT
FROM BOOKING_SUMMARY
GROUP BY HOTEL_NAME
ORDER BY TOTAL_REVENUE DESC;

-- ===========================================
-- Report 2: Customer spending Summary
-- ===========================================
--Which customer spent the most money?

CREATE OR REPLACE TABLE CUSTOMER_SPENDING_SUMMARY AS
SELECT
    CUSTOMER_NAME,
    COUNT(*) AS TOTAL_BOOKINGS,
    SUM(AMOUNT) AS TOTAL_SPENT,
    AVG(AMOUNT) AS AVERAGE_SPENT
FROM BOOKING_SUMMARY
GROUP BY CUSTOMER_NAME
ORDER BY TOTAL_SPENT DESC;

--Which room type is the most popular and how much revenue does it generate?
CREATE OR REPLACE TABLE ROOM_POPULARITY_SUMMARY AS
SELECT
    ROOM_TYPE,
    COUNT(*) AS TOTAL_BOOKINGS,
    SUM(AMOUNT) AS TOTAL_REVENUE,
    AVG(AMOUNT) AS AVERAGE_REVENUE
FROM BOOKING_SUMMARY
GROUP BY ROOM_TYPE
ORDER BY TOTAL_BOOKINGS DESC, TOTAL_REVENUE DESC;

