--step 5: creating customer table 
CREATE OR REPLACE TABLE CUSTOMER (
    CUSTOMER_ID INT AUTOINCREMENT PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    PHONE_NUMBER VARCHAR(15),
    DATE_OF_BIRTH DATE,
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    COUNTRY VARCHAR(50),
    CREATED_DATE DATE
);
--step 6: creating hotel table
CREATE OR REPLACE TABLE HOTEL (
    HOTEL_ID INT AUTOINCREMENT PRIMARY KEY,
    HOTEL_NAME VARCHAR(100),
    STAR_RATING NUMBER(1),
    HOTEL_ADDRESS VARCHAR(200),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    COUNTRY VARCHAR(50),
    PHONE_NUMBER VARCHAR(15)
);
--STEP 7: creating room table
CREATE OR REPLACE TABLE ROOM (
    ROOM_ID INT AUTOINCREMENT PRIMARY KEY,
    HOTEL_ID INT,
    ROOM_NUMBER VARCHAR(10),
    ROOM_TYPE VARCHAR(30),
    PRICE_PER_NIGHT NUMBER(10,2),
    CAPACITY INT,
    AVAILABILITY_STATUS VARCHAR(20),

    CONSTRAINT FK_ROOM_HOTEL    --it is a contraint building relationship with table to foreingkey
        FOREIGN KEY (HOTEL_ID)
        REFERENCES HOTEL(HOTEL_ID)
);
-- -- Step 8: Create BOOKING table
-- Stores all hotel booking transactions.
-- This is the central transactional table connecting customers and rooms.
CREATE OR REPLACE TABLE BOOKING (
    BOOKING_ID INT AUTOINCREMENT PRIMARY KEY,
    CUSTOMER_ID INT,
    ROOM_ID INT,
    CHECK_IN_DATE DATE,
    CHECK_OUT_DATE DATE,
    BOOKING_DATE DATE,
    NUMBER_OF_GUESTS INT,
    BOOKING_STATUS VARCHAR(20),

    CONSTRAINT FK_BOOKING_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_BOOKING_ROOM
        FOREIGN KEY (ROOM_ID)
        REFERENCES ROOM(ROOM_ID)
);
--step 9 creating payment table
CREATE OR REPLACE TABLE PAYMENT (
    PAYMENT_ID INT AUTOINCREMENT PRIMARY KEY,
    BOOKING_ID INT,
    PAYMENT_DATE DATE,
    PAYMENT_MODE VARCHAR(30),
    AMOUNT NUMBER(10,2),
    PAYMENT_STATUS VARCHAR(20),
    TRANSACTION_ID VARCHAR(100),

    CONSTRAINT FK_PAYMENT_BOOKING
        FOREIGN KEY (BOOKING_ID)
        REFERENCES BOOKING(BOOKING_ID)
);

